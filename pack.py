from cryptography.hazmat.primitives.ciphers import Cipher,algorithms
import os
H=os.path.dirname(os.path.abspath(__file__));E=os.path.join(H,'export','');OUT=os.path.join(H,'private','')
key=secrets.token_bytes(32)
def enc(data):
    nonce=secrets.token_bytes(12);c=Cipher(algorithms.ChaCha20(key,b'\0\0\0\0'+nonce),mode=None).encryptor()
    return nonce+c.update(zlib.compress(data,9))
idx=json.load(open(E+'_index.json'))
blobs=[];offs={};pos=0
for c in idx['charts']:
    b=enc(open(E+c['id']+'.svg','rb').read());offs[c['id']]=[pos,len(b)];blobs.append(b);pos+=len(b)
idx['offsets']=offs
head=enc(json.dumps(idx,separators=(',',':')).encode())
with open(OUT+'charts.bin','wb') as f:
    f.write(b'OPB1');f.write(struct.pack('<I',len(head)));f.write(head)
    for b in blobs: f.write(b)
# key split into two shares so it never appears as one literal
a=secrets.token_bytes(32);b=bytes(x^y for x,y in zip(key,a))
open(os.path.join(H,'private','key.rs'),'w').write(
 "// generated by pack.py\npub(crate) const KA: [u8; 32] = %s;\npub(crate) const KB: [u8; 32] = %s;\n"%(list(a),list(b)))
print('bundle MB',round(os.path.getsize(OUT+'charts.bin')/1e6,1),'charts',len(idx['charts']))
